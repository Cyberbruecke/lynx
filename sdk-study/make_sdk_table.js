#!/usr/bin/env node
"use strict";
// Emit results/sdk-eval-table.tex: the 31 eval SDKs (group:"code" with ground truth), their GT endpoint
// count, and recall/precision per tool as 0-1 FRACTIONS (2 dp), each cell heat-shaded red->yellow->green over
// [0,1] (higher=greener). Colors match the capability matrix (green #137333, red #B00020, gold #E8B300).
// relwarc is omitted (it recovers no SDK endpoint — mention in text). Reads sdk-recall.csv + sdks.json;
// the endpoint-WEIGHTED summary row is read from sdk-by-group.csv (the paper's §5 figure).
const fs = require("fs"), path = require("path");
const R = path.join(__dirname, "results");
const TOOLS = [["linkfinder", "LinkFinder"], ["jsluice", "JSluice"], ["lynx", "LyN-X"]];
const texEsc = (s) => String(s).replace(/([&%$#_{}])/g, "\\$1");

// which SDKs are the eval-31: group "code" AND have ground truth
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, "sdks.json"), "utf8"));
const eval31 = new Set(manifest.sdks.filter((s) => s.group === "code" && fs.existsSync(path.join(__dirname, "gt", `${s.name}.jsonl`))).map((s) => s.name));

// parse sdk-recall.csv -> data[sdk][tool] = {recall, precision, total}
const rows = fs.readFileSync(path.join(R, "sdk-recall.csv"), "utf8").trim().split(/\r?\n/);
const hdr = rows.shift().split(",");
const ci = (n) => hdr.indexOf(n);
const data = {};
for (const line of rows) {
  const c = line.split(",");
  const sdk = c[ci("sdk")];
  if (!eval31.has(sdk)) continue;
  (data[sdk] = data[sdk] || {})[c[ci("tool")]] = { recall: +c[ci("recall")], precision: +c[ci("precision")],
    total: +c[ci("total")], ex: +c[ci("exact")], tp: +c[ci("templated")], emitted: +c[ci("emitted")] };
}
const byGt = (a, b) => (data[b].lynx?.total || 0) - (data[a].lynx?.total || 0);
// Split: SDKs where NO tool recovers anything (recall 0 for all) go to the bottom; the rest are "recoverable".
const allFail = (s) => TOOLS.every(([t]) => (data[s][t]?.recall || 0) === 0);
const recovered = Object.keys(data).filter((s) => !allFail(s)).sort(byGt);
const failed = Object.keys(data).filter(allFail).sort(byGt);
const sdks = [...recovered, ...failed];
if (sdks.length !== 31) console.error(`[!] expected 31 eval SDKs, got ${sdks.length}`);
// endpoint-weighted average over a set: pooled recall = Σ(exact+templated)/Σtotal; pooled precision = Σhits/Σemitted
const wavg = (set, t) => { let rec = 0, tot = 0, hits = 0, emit = 0;
  for (const s of set) { const d = data[s][t]; rec += d.ex + d.tp; tot += d.total; hits += d.precision * d.emitted; emit += d.emitted; }
  return { recall: tot ? rec / tot : 0, precision: emit ? hits / emit : 0, gt: tot }; };

const frac = (x) => (x == null ? "--" : `\\hcell{${(+x).toFixed(2)}}`);   // 2-dp fraction, heat-shaded over [0,1]
const colspec = "l r " + TOOLS.map(() => "rr").join(" ");

// ---- preamble bits (packages must be in YOUR preamble; the defs below are emitted inline, safe to move up) ----
let tex = "% Auto-generated by make_sdk_table.js. PREAMBLE REQUIRES:\n";
tex += "%   \\usepackage[table,dvipsnames]{xcolor}   \\usepackage{pgf}   \\usepackage{booktabs}\n";
tex += "% Cells: recall(R)/precision(P) as 0-1 fractions, heat-shaded red->yellow->green over [0,1]. GT = spec endpoints.\n";
tex += "\\definecolor{capgreen}{HTML}{137333}\n\\definecolor{capred}{HTML}{B00020}\n\\definecolor{capgold}{HTML}{E8B300}\n";
tex += "\\colorlet{heatMin}{capred!22}\\colorlet{heatMid}{capgold!40}\\colorlet{heatMax}{capgreen!30}\n";
tex += "\\providecommand{\\numheat}[3]{%\n";
tex += "  \\begingroup\n";
tex += "    \\pgfmathsetmacro{\\heatDen}{#3-#2}%\n";
tex += "    \\pgfmathtruncatemacro{\\heatDenZero}{\\heatDen==0}%\n";
tex += "    \\ifnum\\heatDenZero=1 \\def\\heatColorExpr{heatMid}%\n";
tex += "    \\else\n";
tex += "      \\pgfmathsetmacro{\\heatT}{(#1-#2)/\\heatDen}%\n";
tex += "      \\pgfmathsetmacro{\\heatTc}{max(0,min(1,\\heatT))}%\n";
tex += "      \\pgfmathtruncatemacro{\\heatLow}{\\heatTc<0.5?1:0}%\n";
tex += "      \\ifnum\\heatLow=1 \\pgfmathtruncatemacro{\\heatPct}{round(100*\\heatTc*2)}\\edef\\heatColorExpr{heatMid!\\heatPct!heatMin}%\n";
tex += "      \\else \\pgfmathtruncatemacro{\\heatPct}{round(100*(\\heatTc-0.5)*2)}\\edef\\heatColorExpr{heatMax!\\heatPct!heatMid}%\n";
tex += "      \\fi\n";
tex += "    \\fi\n";
tex += "    \\expandafter\\cellcolor\\expandafter{\\heatColorExpr}{\\strut #1}%\n";
tex += "  \\endgroup\n}\n";
tex += "\\providecommand{\\hcell}[1]{\\numheat{#1}{0}{1}}%  span hardcoded to [0,1]\n";

tex += `\\begin{tabular}{${colspec}}\n\\toprule\n`;
tex += ` & & ${TOOLS.map(([, d]) => `\\multicolumn{2}{c}{\\textbf{${texEsc(d)}}}`).join(" & ")} \\\\\n`;
tex += TOOLS.map((_, i) => `\\cmidrule(lr){${3 + 2 * i}-${4 + 2 * i}}`).join(" ") + "\n";
tex += `\\textbf{SDK} & \\textbf{GT} & ${TOOLS.map(() => "R & P").join(" & ")} \\\\\n`;

const emitRows = (set) => { for (const sdk of set) {
  const gt = data[sdk].lynx?.total ?? Object.values(data[sdk])[0]?.total ?? 0;
  const cells = TOOLS.map(([t]) => { const d = data[sdk][t]; return `${frac(d && d.recall)} & ${frac(d && d.precision)}`; });
  tex += `${texEsc(sdk)} & ${gt} & ${cells.join(" & ")} \\\\\n`;
} };
const avgRow = (label, set) => {
  const cells = TOOLS.map(([t]) => { const a = wavg(set, t); return `${frac(a.recall)} & ${frac(a.precision)}`; });
  tex += `\\textbf{${label}} & \\textbf{${wavg(set, TOOLS[0][0]).gt}} & ${cells.join(" & ")} \\\\\n`;
};
// recoverable SDKs, their weighted avg, then the all-fail SDKs, then the overall weighted avg
tex += "\\midrule\n";
emitRows(recovered);
tex += "\\midrule\n";
avgRow("Weighted avg (recovered)", recovered);
tex += "\\midrule\n";
emitRows(failed);
tex += "\\midrule\n";
avgRow("Weighted avg (all)", sdks);
tex += "\\bottomrule\n\\end{tabular}\n";
fs.writeFileSync(path.join(R, "sdk-eval-table.tex"), tex);
const oa = wavg(sdks, "lynx"), ra = wavg(recovered, "lynx");
console.log(`wrote ${R}/sdk-eval-table.tex (${sdks.length} SDKs: ${recovered.length} recovered + ${failed.length} all-fail; tools ${TOOLS.map(t => t[1]).join(", ")})`);
console.log(`all-fail SDKs: ${failed.join(", ")}`);
console.log(`LyN-X recall/precision — all: ${oa.recall.toFixed(2)}/${oa.precision.toFixed(2)} | recovered subset: ${ra.recall.toFixed(2)}/${ra.precision.toFixed(2)}`);
